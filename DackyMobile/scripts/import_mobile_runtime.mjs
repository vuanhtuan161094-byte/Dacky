const cityCategory = categoryMeta.get('danh-thanh');
const cityRows = categoryRows['danh-thanh'];
const cityFacts = {};
const citySlots=[];
for(let index=0;index<120;index++){
  const chapterIndex=Math.floor(index/15),localIndex=index%15;
  const citiesInChapter=chapterIndex<3?10:9;
  if(localIndex<citiesInChapter)citySlots.push(`node-${String(index+1).padStart(3,'0')}`);
}
for(const [rowIndex,row] of cityRows.entries()){
  const targetId=citySlots[rowIndex];
  if(!targetId)throw new Error(`No runtime map slot for Mobile city ${row.id}.`);
  const infoBlock=row.details.find(block=>block.k==='cs'&&block.t==='Thông tin');
  const info=Object.fromEntries(infoBlock?.ds||[]);
  const coordinateText=String(info['Toạ độ']||'');
  const coordinateMatch=coordinateText.match(/(-?\d+(?:\.\d+)?)\s*,\s*(-?\d+(?:\.\d+)?)/);
  const coordinates=coordinateMatch?[Number(coordinateMatch[1]),Number(coordinateMatch[2])]:null;
  const mapCoordinate=value=>coordinates?Math.max(2,Math.min(98,Number((value/10).toFixed(1)))):null;
  const guardBlock=row.details.find(block=>block.k==='icon'&&Array.isArray(block.ds));
  const garrison=(guardBlock?.ds||[]).map(guard=>({
    name:String(guard.t||''),
    image:guard.a?new URL(guard.a,'https://dackytruvuong.com').href:'',
    localImage:localAssetPath(guard.a),
    rank:Number(guard.m)||0,
    troopText:String(guard.p||'')
  }));
  const source=(sourceField,value)=>({
    value,
    targetType:Array.isArray(value)?'array':typeof value,
    provenance:{evidence:'VERIFIED_MOBILE',sourceVersion:manifest.catalogVersion,sourceTable:'danh-thanh',sourceField,
      dataHash:cityCategory.fileSha256,schemaHash:indexHash,sourceRecordId:row.id,
      license:'PROJECT_OWNER_AUTHORIZATION_ASSERTED_NO_SPDX',
      permissionEvidence:'Owner authorization in Codex conversation dated 2026-11-25: rights to use found game data/assets for our projects; scope includes public Mobile and legacy data.'}
  });
  cityFacts[targetId]={
    name:source(`muc[${rowIndex}].t`,row.name),
    x:source(`muc[${rowIndex}].d[k=cs,t=Thông tin].ds[Toạ độ]`,mapCoordinate(coordinates?.[0])),
    y:source(`muc[${rowIndex}].d[k=cs,t=Thông tin].ds[Toạ độ]`,mapCoordinate(coordinates?.[1])),
    mobileCityId:source(`muc[${rowIndex}].i`,row.id),
    mobileImage:source(`muc[${rowIndex}].a`,localAssetPath(row.image||'')),
    mobileCityType:source(`muc[${rowIndex}].d[k=cs,t=Thông tin].ds[Loại]`,String(info['Loại']||'')),
    mobileFaction:source(`muc[${rowIndex}].d[k=cs,t=Thông tin].ds[Phe]`,String(info['Phe']||'')),
    mobileWallLevel:source(`muc[${rowIndex}].d[k=cs,t=Thông tin].ds[Cấp tường thành]`,Number(info['Cấp tường thành'])||0),
    mobileOfficialLevel:source(`muc[${rowIndex}].d[k=cs,t=Thông tin].ds[Cấp quan]`,Number(info['Cấp quan'])||0),
    mobileCoordinates:source(`muc[${rowIndex}].d[k=cs,t=Thông tin].ds[Toạ độ]`,coordinates),
    mobileGarrison:source(`muc[${rowIndex}].d[k=icon,t=Quân trấn thủ].ds`,garrison),
    sourceFieldStatus:source(`muc[${rowIndex}]`,'VERIFIED_MOBILE')
  };
}

const troopCategory = categoryMeta.get('binh-chung');
const troopRows = categoryRows['binh-chung'];
const troopFacts = {};
const troopTargets = [
  'troop-02','troop-03','troop-06','troop-10','troop-04','troop-05','troop-07','troop-08','troop-09',
  'troop-11','troop-12','troop-13','troop-14','troop-16','troop-17','troop-18','troop-19','troop-20',
  'troop-21','troop-22','troop-23','troop-24','troop-25','troop-26','troop-27'
];
const sourceClassRole = (value = '') => {
  const role = value.toLocaleLowerCase('vi');
  if (role.includes('đao thuẫn') || role.includes('trường kích')) return 'bộ binh';
  if (role.includes('cung tiễn')) return 'xạ thủ';
  if (role.includes('kỵ')) return 'kỵ binh';
  return 'bộ binh';
};
for (const [rowIndex, row] of troopRows.entries()) {
  const stats = row.details.find((block) => block.k === 'cs' && block.t === 'Chỉ số')?.ds || [];
  const details = Object.fromEntries(stats);
  const counterBlock = row.details.find((block) => block.k === 'bang' && Array.isArray(block.dong));
  const counterRows = (counterBlock?.dong || []).map(([target, rate]) => ({
    target: String(target),
    rate: String(rate),
    modifier: Number(String(rate).replace('−', '-').replace('%', '')) / 100
  }));
  const infoBlock = row.details.find((block) => block.k === 'cs' && block.t === 'Thông tin');
  const info = Object.fromEntries(infoBlock?.ds || []);
  const sourceCounterRole = sourceClassRole(counterRows[0]?.target?.split('(')[0] || '');
  const lane = sourceClassRole(row.filters.cls)==='xạ thủ'?'rear':'front';
  const source = (sourceField, value) => ({
    value,
    targetType: Array.isArray(value) ? 'array' : typeof value,
    provenance: {
      evidence: 'VERIFIED_MOBILE',
      sourceVersion: manifest.catalogVersion,
      sourceTable: 'binh-chung',
      sourceField,
      dataHash: troopCategory.fileSha256,
      schemaHash: indexHash,
      sourceRecordId: row.id,
      license: 'PROJECT_OWNER_AUTHORIZATION_ASSERTED_NO_SPDX',
      permissionEvidence: 'Owner authorization in Codex conversation dated 2026-11-25: rights to use found game data/assets for our projects; scope includes public Mobile and legacy data.'
    }
  });
  troopFacts[troopTargets[rowIndex]] = {
    name: source(`muc[${rowIndex}].t`, row.name),
    mobileImage: source(`muc[${rowIndex}].a`, localAssetPath(row.image || '')),
    role: source(`muc[${rowIndex}].f.cls`, sourceClassRole(row.filters.cls)),
    lane: source(`muc[${rowIndex}].f.cls`, lane),
    counter: source(`muc[${rowIndex}].d[k=bang,t=Khắc chế khi tấn công].dong[0]`, sourceCounterRole),
    mobileSourceId: source(`muc[${rowIndex}].i`, row.id),
    mobileClass: source(`muc[${rowIndex}].f.cls`, row.filters.cls || ''),
    mobileFaction: source(`muc[${rowIndex}].f.phe`, row.filters.phe || ''),
    attack: source(`muc[${rowIndex}].d[k=cs,t=Chỉ số]`, Number(details['Công']) || 0),
    defense: source(`muc[${rowIndex}].d[k=cs,t=Chỉ số]`, Number(details['Thủ']) || 0),
    speed: source(`muc[${rowIndex}].d[k=cs,t=Chỉ số]`, Number(details['Tốc']) || 0),
    mobileLife: source(`muc[${rowIndex}].d[k=cs,t=Chỉ số]`, Number(details['Máu']) || 0),
    mobileCarry: source(`muc[${rowIndex}].d[k=cs,t=Chỉ số]`, Number(details['Tải']) || 0),
    mobileUpkeep: source(`muc[${rowIndex}].d[k=cs,t=Chỉ số]`, Number(details['Lương']) || 0),
    mobilePopulation: source(`muc[${rowIndex}].d[k=cs,t=Thông tin]`, Number(info['Chiếm dân']) || 0),
    mobileCounterRows: source(`muc[${rowIndex}].d[k=bang,t=Khắc chế khi tấn công].dong`, counterRows),
    sourceFieldStatus: source(`muc[${rowIndex}]`, 'VERIFIED_MOBILE')
  };
}

const heroCategory = categoryMeta.get('than-tien');
const normalizeHeroName = (value) => String(value).normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLocaleLowerCase('vi').replace(/[^a-z0-9]/g, '');
const heroSourceByName = new Map();
for (const row of categoryRows['than-tien']) {
  const key = normalizeHeroName(row.name);
  if (!heroSourceByName.has(key)) heroSourceByName.set(key, row);
}
const canonicalHeroes = [
  'Khương Tử Nha','Na Tra','Dương Tiễn','Hoàng Phi Hổ','Lôi Chấn Tử','Đặng Thiền Ngọc',
  'Long Cát Công Chúa','Vi Na','Hàn Độc Long','Tô Hộ','Bạch Hạc Đồng Tử','Ân Giao',
  'Tân Hoàn','Triệu Công Minh','Văn Trọng','Thân Công Báo','Cơ Phát','Thạch Cơ'
];
const heroFacts = {};
for (const [heroIndex, name] of canonicalHeroes.entries()) {
  const row = heroSourceByName.get(normalizeHeroName(name));
  if (!row) continue;
  const sourceIndex = categoryRows['than-tien'].indexOf(row);
  const infoBlock = row.details.find((block) => block.k === 'cs' && block.t === 'Thông tin');
  const info = Object.fromEntries(infoBlock?.ds || []);
  const statsBlock = row.details.find((block) => block.k === 'cs' && block.t === 'Chỉ số khởi điểm');
  const abilities = row.details.filter((block) => block.k === 'kn').flatMap((block) => (block.ds || []).map((item) => ({
    name: String(item.t || ''), description: String(item.v || ''), rank: Number(item.m) || 0
  })));
  const source = (sourceField, value) => ({
    value,
    targetType: Array.isArray(value) ? 'array' : typeof value,
    provenance: {
      evidence: 'VERIFIED_MOBILE', sourceVersion: manifest.catalogVersion, sourceTable: 'than-tien', sourceField,
      dataHash: heroCategory.fileSha256, schemaHash: indexHash, sourceRecordId: row.id,
      license: 'PROJECT_OWNER_AUTHORIZATION_ASSERTED_NO_SPDX',
      permissionEvidence: 'Owner authorization in Codex conversation dated 2026-11-25: rights to use found game data/assets for our projects; scope includes public Mobile and legacy data.'
    }
  });
  heroFacts[`hero-${String(heroIndex + 1).padStart(2, '0')}`] = {
    name: source(`muc[${sourceIndex}].t`, row.name),
    mobileSourceId: source(`muc[${sourceIndex}].i`, row.id),
    mobileImage: source(`muc[${sourceIndex}].a`, row.localImage),
    mobileFaction: source(`muc[${sourceIndex}].f.giao`, String(row.filters.giao || '')),
    mobileOccupation: source(`muc[${sourceIndex}].f.nghe`, String(info['Nghề'] || row.filters.nghe || '')),
    mobileBaseStats: source(`muc[${sourceIndex}].d[k=cs,t=Chỉ số khởi điểm].ds`, (statsBlock?.ds || []).map(([label, value]) => ({ label: String(label), value }))),
    mobileAbilities: source(`muc[${sourceIndex}].d[k=kn].ds`, abilities),
    mobileSignature: source(`muc[${sourceIndex}].d[k=cs,t=Thông tin].ds[Danh hiệu]`, String(info['Danh hiệu'] || ''))
  };
}

const permissionText = 'Owner authorization in Codex conversation dated 2026-11-25: rights to use found game data/assets for our projects; scope includes public Mobile and legacy data.';
const approved = `// Generated by scripts/import_mobile_runtime.mjs from checksum-verified Mobile catalogs.\nexport const SOURCE_REUSE_DECISION = Object.freeze({\n  status: 'AUTHORIZED_FOR_RUNTIME',\n  license: 'PROJECT_OWNER_AUTHORIZATION_ASSERTED_NO_SPDX',\n  permissionEvidence: ${JSON.stringify(permissionText)}\n});\n\nexport const APPROVED_SOURCE_FACTS = Object.freeze(${JSON.stringify({ buildings: facts, technologies: techFacts, troops: troopFacts, worldNodes: cityFacts, heroes: heroFacts })});\n`;
await writeFile(resolve(appDir, 'src/approved-source-data.js'), approved);
console.log(`Imported ${Object.values(categoryRows).reduce((sum, rows) => sum + rows.length, 0)} Mobile records; attached ${Object.keys(facts).length} building tables, ${Object.keys(techFacts).length} technology tables, ${Object.keys(troopFacts).length} troop profiles, and ${Object.keys(cityFacts).length} city identities, and ${Object.keys(heroFacts).length} canonical hero profiles to runtime.`);
