import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const appDir = resolve(scriptDir, '..');
const privateDir = resolve(appDir, 'input-private/mobile_reference');
const manifest = JSON.parse(await readFile(resolve(privateDir, 'manifest.json'), 'utf8'));
const indexBytes = await readFile(resolve(privateDir, 'index.json'));
const index = JSON.parse(indexBytes);
const indexHash = createHash('sha256').update(indexBytes).digest('hex');
if (indexHash !== manifest.indexSha256) throw new Error('Mobile index checksum does not match the capture manifest.');
const sourceAssetManifest = JSON.parse(await readFile(resolve(appDir, 'assets/mobile-source-manifest.json'), 'utf8'));
const sourceAssets = new Map(sourceAssetManifest.assets.map(asset => [asset.path, asset]));

const localAssetPath = (asset) => {
  if (!asset) return '';
  const url = new URL(asset, manifest.dataBaseUrl);
  if (url.hostname !== 'dackytruvuong.com') throw new Error(`Unexpected Mobile asset host: ${url.hostname}`);
  return `./assets/mobile-source${url.pathname}`;
};
const categoryRows = {};
for (const category of manifest.categories) {
  const bytes = await readFile(resolve(privateDir, `${category.id}.json`));
  const hash = createHash('sha256').update(bytes).digest('hex');
  if (hash !== category.fileSha256) throw new Error(`${category.id} checksum does not match the capture manifest.`);
  const source = JSON.parse(bytes);
  if (!Array.isArray(source.muc) || source.muc.length !== category.count) {
    throw new Error(`${category.id} row count does not match the capture manifest.`);
  }
  categoryRows[category.id] = source.muc.map((row, indexInCategory) => {
    const detail = (key) => row.d?.find((block) => block.k === key);
    const descriptions = (row.d || []).filter((block) => block.k === 'mo').map((block) => block.v).filter(Boolean);
    const paths = {
      id: `muc[${indexInCategory}].i`,
      name: `muc[${indexInCategory}].t`,
      image: `muc[${indexInCategory}].a`,
      quality: `muc[${indexInCategory}].m`,
      section: `muc[${indexInCategory}].p`,
      tags: `muc[${indexInCategory}].n`,
      filters: `muc[${indexInCategory}].f`,
      description: `muc[${indexInCategory}].d[k=mo].v`,
      details: `muc[${indexInCategory}].d`
    };
    const fields = {
      id: String(row.i),
      name: String(row.t || ''),
      image: row.a ? new URL(row.a, manifest.dataBaseUrl).href : null,
      localImage: localAssetPath(row.a),
      quality: row.m ?? null,
      section: row.p ?? null,
      tags: row.n || [],
      filters: row.f || {},
      description: descriptions.join('\n\n'),
      details: row.d || []
    };
    return { ...fields, fieldProvenance: paths };
  });
}

