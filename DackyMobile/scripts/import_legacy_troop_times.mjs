import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { APPROVED_SOURCE_FACTS, SOURCE_REUSE_DECISION } from '../src/approved-source-data.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const inputPath = path.join(root, 'input-private', 'normalized_legacy', '147-soldierinfo.json');
const outputPath = path.join(root, 'src', 'legacy-troop-time-catalog.js');
const sourceFields = ['TrainSpendDay', 'TrainSpendHour', 'TrainSpendMinute', 'TrainSpendSecond'];
const HASH = /^[a-f0-9]{40}$/i;

async function importLegacyTroopTimes() {
  if (SOURCE_REUSE_DECISION.status !== 'AUTHORIZED_FOR_RUNTIME') {
    throw new Error('Legacy troop time import requires the recorded owner authorization.');
  }
  const source = JSON.parse(await readFile(inputPath, 'utf8'));
  if (source.status !== 'PRIVATE_LEGACY_RESEARCH_NOT_RUNTIME_APPROVED'
      || !Array.isArray(source.records) || !Array.isArray(source.schema)
      || !/^[a-f0-9]{40}$/i.test(source.sourceCommit || '')) {
    throw new Error('Legacy troop table is not a pinned normalized research table.');
  }
  const columns = Object.fromEntries(source.schema.map(column => [column.name, column.provenance]));
  const descriptors = sourceFields.map(field => columns[field]);
  for (const descriptor of descriptors) {
    if (!descriptor || !HASH.test(descriptor.dataBlobSha1 || '')
        || !HASH.test(descriptor.schemaBlobSha1 || '') || !HASH.test(descriptor.indexBlobSha1 || '')) {
      throw new Error('Legacy troop time fields lack pinned data/schema/index provenance.');
    }
  }
  if (new Set(descriptors.map(row => row.dataBlobSha1)).size !== 1
      || new Set(descriptors.map(row => row.schemaBlobSha1)).size !== 1
      || new Set(descriptors.map(row => row.indexBlobSha1)).size !== 1) {
    throw new Error('Legacy troop time fields do not share one pinned table source.');
  }
  const legacyById = new Map(source.records.map(row => [String(row.SoldierID), row]));
  const facts = {};
  for (const [targetId, fields] of Object.entries(APPROVED_SOURCE_FACTS.troops || {})) {
    const sourceId = String(fields.mobileSourceId?.value || '');
    const row = legacyById.get(sourceId);
    if (!row) continue;
    const parts = sourceFields.map(field => Number(row[field]));
    if (parts.some(value => !Number.isSafeInteger(value) || value < 0)) {
      throw new Error(`Invalid legacy training duration for SoldierID ${sourceId}.`);
    }
    const [days, hours, minutes, seconds] = parts;
    const trainSeconds = days * 86_400 + hours * 3_600 + minutes * 60 + seconds;
    const provenance = {
      evidence: 'VERIFIED_LEGACY',
      sourceVersion: `Dacky legacy MySQL snapshot ${source.sourceCommit.slice(0, 10)}`,
      sourceCommit: source.sourceCommit,
      sourceTable: source.sourceTable,
      sourceField: sourceFields.join('+'),
      dataHash: descriptors[0].dataBlobSha1,
      schemaHash: descriptors[0].schemaBlobSha1,
      indexHash: descriptors[0].indexBlobSha1,
      sourceRecordId: sourceId,
      license: SOURCE_REUSE_DECISION.license,
      permissionEvidence: SOURCE_REUSE_DECISION.permissionEvidence
    };
    facts[targetId] = {
      trainSeconds: { value: trainSeconds, targetType: 'number', provenance }
    };
  }
  if (Object.keys(facts).length !== 24) {
    throw new Error(`Expected 24 shared Mobile/legacy troop IDs; mapped ${Object.keys(facts).length}.`);
  }
  const metadata = {
    status: 'VERIFIED_LEGACY_TRAINING_TIME_FIELD_ADAPTER',
    sourceVersion: `Dacky legacy MySQL snapshot ${source.sourceCommit.slice(0, 10)}`,
    sourceCommit: source.sourceCommit,
    sourceTable: source.sourceTable,
    sourceFields,
    importedRecords: Object.keys(facts).length,
    unit: 'seconds',
    conversion: 'day*86400 + hour*3600 + minute*60 + second',
    permission: SOURCE_REUSE_DECISION
  };
  await writeFile(outputPath,
    `// Generated by scripts/import_legacy_troop_times.mjs from pinned, normalized legacy records.\nexport const LEGACY_TROOP_TIME_SOURCE = Object.freeze(${JSON.stringify(metadata)});\nexport const LEGACY_TROOP_TIME_FACTS = Object.freeze(${JSON.stringify(facts)});\n`,
    'utf8');
  return { importedRecords: Object.keys(facts).length, sourceTable: source.sourceTable, sourceCommit: source.sourceCommit };
}

const result = await importLegacyTroopTimes();
console.log(JSON.stringify(result));
